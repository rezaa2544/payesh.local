#!/usr/bin/env node
/* ردیف ۱۷۹ — «چه چیزهایی تازه است؟» در همهٔ پنل‌ها از یک منبع: RELEASE_NOTES.json
 *
 *   node tools/gen-whats-new-179.mjs          ⇒ نوشتن خروجی‌ها
 *   node tools/gen-whats-new-179.mjs --check  ⇒ فقط بررسی هم‌ترازی (کد خروج ۱ اگر کهنه است)
 *
 * خروجی‌ها:
 *   apps/payesh/packages/payesh_update/lib/src/whats_new_data.dart  (پنل مالک + اپ مدرسه)
 *   client/app.js بین نشانه‌های WHATS_NEW:BEGIN/END                 (پنل وب)
 *   apps/owner-panel/web/app.js بین OWNER_WHATS_NEW:BEGIN/END        (پنل وب مالک — ردیف ۱۸۱)
 * هر خط یا رشته است (همهٔ پنل‌ها) یا {t, for:[owner|school|web]}.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const KEEP = 15; /* نسخه‌های اخیر که داخل برنامه‌ها می‌مانند */
export const AUDIENCES = ['owner', 'school', 'web'];

export function semverCmp(a, b) {
  const pa = String(a).split('.').map(Number); const pb = String(b).split('.').map(Number);
  for (let i = 0; i < 3; i++) { const d = (pa[i] || 0) - (pb[i] || 0); if (d) return d; }
  return 0;
}

export function normalize(all) {
  return Object.keys(all)
    .filter(v => /^\d+\.\d+\.\d+$/.test(v))
    .sort((a, b) => semverCmp(b, a))
    .slice(0, KEEP)
    .map(v => ({
      v,
      items: (all[v] || []).map(n => (typeof n === 'string'
        ? { t: n, for: AUDIENCES }
        : { t: String(n.t || ''), for: Array.isArray(n.for) && n.for.length ? n.for.filter(a => AUDIENCES.includes(a)) : AUDIENCES }))
        .filter(n => n.t),
    }))
    .filter(r => r.items.length);
}

const dq = s => "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n') + "'";

export function dartSource(rel) {
  const out = [
    '// GENERATED by tools/gen-whats-new-179.mjs from RELEASE_NOTES.json — do not edit by hand.',
    '// ردیف ۱۷۹: یادداشت‌های نسخه برای پنجرهٔ «چه چیزهایی تازه است؟».',
    '// dart format off',
    '',
    "import 'whats_new.dart';",
    '',
    'const List<ReleaseNote> kReleaseNotes = [',
  ];
  for (const r of rel) {
    out.push(`  ReleaseNote(${dq(r.v)}, [`);
    for (const n of r.items) {
      const aud = n.for.length === AUDIENCES.length ? '' : `, {${n.for.map(a => 'NoteAudience.' + a).join(', ')}}`;
      out.push(`    NoteItem(${dq(n.t)}${aud}),`);
    }
    out.push('  ]),');
  }
  out.push('];', '');
  return out.join('\n');
}

export function webBlock(rel) {
  const web = rel
    .map(r => ({ v: r.v, n: r.items.filter(n => n.for.includes('web') || n.for.includes('school')).map(n => n.t) }))
    .filter(r => r.n.length);
  return '/* WHATS_NEW:BEGIN — ساخته‌شده با tools/gen-whats-new-179.mjs؛ دستی ویرایش نکنید */\n'
    + 'const WHATS_NEW = ' + JSON.stringify(web) + ';\n'
    + '/* WHATS_NEW:END */';
}

const BLOCK_RE = /\/\* WHATS_NEW:BEGIN[\s\S]*?\/\* WHATS_NEW:END \*\//;
const OWNER_RE = /\/\* OWNER_WHATS_NEW:BEGIN[\s\S]*?\/\* OWNER_WHATS_NEW:END \*\//;

/* ردیف ۱۸۱: پنل وب مالک — فقط خط‌های مخاطب owner (۵ نسخهٔ اخیر) */
export function ownerBlock(rel) {
  const own = rel
    .map(r => ({ v: r.v, n: r.items.filter(n => n.for.includes('owner')).map(n => n.t) }))
    .filter(r => r.n.length)
    .slice(0, 5);
  return '/* OWNER_WHATS_NEW:BEGIN — ساخته‌شده با tools/gen-whats-new-179.mjs؛ دستی ویرایش نکنید */\n'
    + '  var OWNER_WHATS_NEW = ' + JSON.stringify(own) + ';\n'
    + '  /* OWNER_WHATS_NEW:END */';
}

export function build(root = ROOT) {
  const all = JSON.parse(fs.readFileSync(path.join(root, 'RELEASE_NOTES.json'), 'utf8'));
  const rel = normalize(all);
  const dartFile = path.join(root, 'apps/payesh/packages/payesh_update/lib/src/whats_new_data.dart');
  const appFile = path.join(root, 'client/app.js');
  const app = fs.readFileSync(appFile, 'utf8');
  if (!BLOCK_RE.test(app)) throw new Error('client/app.js: WHATS_NEW block missing');
  const ownerFile = path.join(root, 'apps/owner-panel/web/app.js');
  const owner = fs.readFileSync(ownerFile, 'utf8');
  if (!OWNER_RE.test(owner)) throw new Error('apps/owner-panel/web/app.js: OWNER_WHATS_NEW block missing');
  return [
    { file: dartFile, want: dartSource(rel) },
    { file: appFile, want: app.replace(BLOCK_RE, webBlock(rel)) },
    { file: ownerFile, want: owner.replace(OWNER_RE, ownerBlock(rel)) },
  ];
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const { file, want } of build()) {
    const have = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (have === want) continue;
    stale++;
    if (check) console.error('stale: ' + path.relative(ROOT, file));
    else fs.writeFileSync(file, want);
  }
  if (check && stale) { console.error('run: node tools/gen-whats-new-179.mjs'); process.exit(1); }
  console.log(check ? 'whats-new: in sync' : `whats-new: wrote ${stale} file(s)`);
}
