#!/usr/bin/env node
// gen-mozilla-roots.mjs — regenerates apps/payesh/packages/payesh_secure/lib/src/mozilla_roots.dart
// from curl's extract of the Mozilla CA store (https://curl.se/docs/caextract.html).
//
//   curl -sSLO https://curl.se/ca/cacert.pem && curl -sSLO https://curl.se/ca/cacert.pem.sha256
//   sha256sum -c cacert.pem.sha256
//   node tools/win7/gen-mozilla-roots.mjs cacert.pem
//
// Row 168: Windows 7 / 8 / 8.1 ship an old root store that Windows normally tops up on demand,
// which Dart (BoringSSL reads the store directly) never triggers — github.com, the S3 host and
// most tunnel hosts then fail with CERTIFICATE_VERIFY_FAILED. The app adds these roots on those
// Windows versions only (legacy_windows_trust.dart).
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = path.join(ROOT, 'apps/payesh/packages/payesh_secure/lib/src/mozilla_roots.dart');
const src = process.argv[2];
if (!src) throw new Error('usage: gen-mozilla-roots.mjs cacert.pem');
const text = fs.readFileSync(src, 'utf8');
const asOf = (text.match(/Certificate data from Mozilla as of: (.+)/) || [])[1];
if (!asOf) throw new Error('not a curl cacert.pem (no "as of" line)');
const sha = crypto.createHash('sha256').update(fs.readFileSync(src)).digest('hex');
const re = /(?:^|\n)([^\n=#][^\n]*)\n=+\n(?:#[^\n]*\n)*(-----BEGIN CERTIFICATE-----\n[\s\S]*?-----END CERTIFICATE-----)/g;
const certs = [];
for (let m; (m = re.exec(text)); ) {
  const pem = m[2].trim();
  const x = new crypto.X509Certificate(pem);
  if (!x.ca) throw new Error(`${m[1]}: not a CA certificate`);
  if (new Date(x.validTo) < new Date()) continue; // never ship an expired root
  certs.push({ name: m[1].trim(), pem, until: x.validTo });
}
if (certs.length < 100) throw new Error(`only ${certs.length} roots parsed`);
const lines = [
  '// GENERATED by tools/win7/gen-mozilla-roots.mjs — do not edit.',
  `// Mozilla CA store as extracted by curl, "as of ${asOf}" (cacert.pem sha256 ${sha}).`,
  '// Used only on Windows 7 / 8 / 8.1 (legacy_windows_trust.dart, row 168).',
  '',
  '/// Mozilla root certificates (PEM), one per entry.',
  'const List<String> mozillaRootPems = [',
];
for (const c of certs) {
  lines.push(`  // ${c.name.replace(/[^\x20-\x7e]/g, '?')} — until ${c.until}`);
  lines.push(`  '''\n${c.pem}\n''',`);
}
lines.push('];', '');
lines.push(`/// Number of roots in [mozillaRootPems] (checked by the tests).`);
lines.push(`const int mozillaRootCount = ${certs.length};`, '');
fs.writeFileSync(OUT, lines.join('\n'));
console.log(`wrote ${path.relative(ROOT, OUT)}: ${certs.length} roots (as of ${asOf})`);
