#!/usr/bin/env node
'use strict';
/* ═══════════════════════════════════════════════════════════════════
   Row 78 — signed native auto-update: publisher tool + cross-language
   contract. The Dart verifier (payesh_secure/lib/src/native_update.dart,
   test/native_update_test.dart NU-01..NU-10, run by native-client.yml) must
   reach the same decision as the JS reference on every vector.

     NU78-01  vectors are deterministic (regenerated byte for byte)
     NU78-02  JS reference reaches the expected decision on all 14 vectors
     NU78-03  publisher key: keygen refuses a Git work tree, writes 0600, never
              overwrites; sign → verify round trip; sign refuses a bad manifest
     NU78-04  NEGATIVE: a bad artifact hash / size never matches the signed manifest
     NU78-05  no publisher private key in the app or in the repository
     NU78-06  Dart side mirrors the rules (pilot default OFF, https only, rollback
              floor, 503 kill-switch, staging deletes on mismatch) and its test
              iterates every vector
     NU78-07  mutants: dropping any one rule of the JS reference turns a vector red
   ═══════════════════════════════════════════════════════════════════ */
const fs = require('fs');
const os = require('os');
const path = require('path');
const crypto = require('crypto');
const { spawnSync } = require('child_process');
const { pathToFileURL } = require('url');

const ROOT = path.resolve(__dirname, '..');
const TOOL = path.join(ROOT, 'tools/native-update-78.mjs');
const VEC = path.join(ROOT, 'docs/cloud/contracts/native-update-vectors-78.json');
const DART_LIB = path.join(ROOT, 'apps/payesh/packages/payesh_secure/lib/src/native_update.dart');
const DART_TEST = path.join(ROOT, 'apps/payesh/packages/payesh_secure/test/native_update_test.dart');

let passed = 0, failed = 0;
async function check(id, desc, fn) {
  try { const d = await fn(); passed++; console.log(`PASS  ${id}  ${desc}  → ${d === undefined ? 'ok' : d}`); }
  catch (e) { failed++; console.log(`FAIL  ${id}  ${desc}  → ${String((e && e.message) || e)}`); }
}
const assert = (c, m) => { if (!c) throw new Error(m); };
const run = (args, opts = {}) => spawnSync(process.execPath, [TOOL, ...args], { encoding: 'utf8', ...opts });

function label(r) { return r.decision === 'refused' ? 'refused:' + r.code : r.decision === 'halted' ? 'halted:' + r.reason : r.decision; }
function outcomes(mod, v) {
  const pub = Buffer.from(v.test_public_key_b64, 'base64');
  return v.cases.map(c => [c, label(mod.evaluate(Buffer.from(c.envelope_text), {
    keys: { [v.test_key_id]: pub }, channel: v.device.channel, platform: v.device.platform,
    installed: v.device.installed_build, highest: v.device.highest_seen_build, now: v.device.now,
  }))]);
}

(async () => {
  console.log(`# row 78 native auto-update — node ${process.version}`);
  const mod = await import(pathToFileURL(TOOL).href);
  const v = JSON.parse(fs.readFileSync(VEC, 'utf8'));

  await check('NU78-01', 'vectors are deterministic (regenerated byte for byte)', () => {
    const r = run(['vectors', '--check']);
    assert(r.status === 0, r.stderr || r.stdout);
    assert(JSON.stringify(mod.buildVectors(), null, 2) + '\n' === fs.readFileSync(VEC, 'utf8'), 'in-process build differs');
    return `${v.cases.length} vectors, key_id ${v.test_key_id}`;
  });

  await check('NU78-02', 'JS reference reaches the expected decision on every vector', () => {
    const bad = outcomes(mod, v).filter(([c, got]) => got !== c.expect).map(([c, got]) => `${c.id}: ${got} != ${c.expect}`);
    assert(!bad.length, bad.join('; '));
    const kinds = new Set(v.cases.map(c => c.expect.split(':')[0]));
    assert(['available', 'up_to_date', 'halted', 'refused'].every(k => kinds.has(k)), 'every decision kind covered');
    return `${v.cases.length}/${v.cases.length}, ${v.cases.filter(c => c.expect.startsWith('refused')).length} refusals`;
  });

  await check('NU78-03', 'publisher key: keygen refuses a Git work tree, writes 0600, never overwrites; sign → verify; sign refuses a bad manifest', () => {
    const inRepo = run(['keygen', '--out', path.join(ROOT, 'docs')]);
    assert(inRepo.status === 2 && /inside a Git work tree/.test(inRepo.stderr), 'keygen inside the repo must be refused: ' + inRepo.stderr);
    const d = fs.mkdtempSync(path.join(os.tmpdir(), 'nu78-'));
    try {
      const k = run(['keygen', '--out', d]);
      assert(k.status === 0, k.stderr);
      const info = JSON.parse(k.stdout);
      const pem = path.join(d, 'payesh-update-signing.pem');
      if (process.platform !== 'win32') assert((fs.statSync(pem).mode & 0o777) === 0o600, 'pem mode ' + (fs.statSync(pem).mode & 0o777).toString(8));
      assert(run(['keygen', '--out', d]).status === 2, 'second keygen must refuse to overwrite');
      const man = JSON.parse(Buffer.from(JSON.parse(v.cases[0].envelope_text).manifest_b64, 'base64'));
      fs.writeFileSync(path.join(d, 'm.json'), JSON.stringify(man));
      const s = run(['sign', '--key', pem, '--manifest', path.join(d, 'm.json'), '--out', path.join(d, 'e.json')]);
      assert(s.status === 0, s.stderr);
      const ok = run(['verify', '--pub', info.public_key_b64, '--envelope', path.join(d, 'e.json'), '--installed', '57', '--highest', '57', '--now', v.device.now]);
      assert(ok.status === 0 && JSON.parse(ok.stdout).decision === 'available', ok.stdout + ok.stderr);
      const wrong = run(['verify', '--pub', v.test_public_key_b64, '--envelope', path.join(d, 'e.json'), '--now', v.device.now]);
      assert(wrong.status === 1 && /upd_unknown_key/.test(wrong.stdout), 'a different pinned key must refuse');
      fs.writeFileSync(path.join(d, 'bad.json'), JSON.stringify({ ...man, artifacts: { android: { ...man.artifacts.android, url: 'http://x/a.apk' } } }));
      const sb = run(['sign', '--key', pem, '--manifest', path.join(d, 'bad.json')]);
      assert(sb.status === 1 && /https/.test(sb.stderr), 'sign must refuse an http artifact');
      return `key_id ${info.key_id}, 0600, round trip ok`;
    } finally { fs.rmSync(d, { recursive: true, force: true }); }
  });

  await check('NU78-04', 'NEGATIVE: a flipped byte or a changed length never matches the signed artifact hash/size', () => {
    const art = Buffer.from(v.artifact_b64, 'base64');
    const sha = b => crypto.createHash('sha256').update(b).digest('hex');
    assert(sha(art) === v.artifact_sha256, 'vector artifact hash');
    const flipped = Buffer.from(art); flipped[7] ^= 1;
    assert(sha(flipped) !== v.artifact_sha256, 'flipped byte must not match');
    const man = JSON.parse(Buffer.from(JSON.parse(v.cases[0].envelope_text).manifest_b64, 'base64'));
    assert(man.artifacts.android.size === art.length && man.artifacts.android.sha256 === v.artifact_sha256, 'manifest pins hash + size');
    return 'hash + size pinned; Dart NU-05 deletes the partial file';
  });

  await check('NU78-05', 'no publisher private key in the app or the repository', () => {
    const files = spawnSync('git', ['ls-files'], { cwd: ROOT, encoding: 'utf8' }).stdout.split('\n').filter(Boolean);
    /* the three files below only contain the marker as a detection pattern */
    const PATTERN_ONLY = new Set(['apps/owner-panel/tests/packaging.test.js', 'tools/security-scan-48.mjs', 'tools/semgrep/rules.yml', 'tests/native-update-78.js']);
    const hits = files.filter(f => !PATTERN_ONLY.has(f) && /\.(pem|key|dart|js|mjs|json|ya?ml|txt|md)$/.test(f))
      .filter(f => { try { return fs.readFileSync(path.join(ROOT, f), 'utf8').includes('PRIVATE KEY-----'); } catch { return false; } });
    assert(!hits.length, 'private key material: ' + hits.join(', '));
    const appPem = files.filter(f => f.startsWith('apps/payesh/') && /\.(pem|p8|pk8)$/.test(f));
    assert(!appPem.length, 'key files in the app: ' + appPem.join(', '));
    assert(/TEST key derived from a public label/.test(v._comment), 'vectors must label the key as TEST');
    return `${files.length} tracked files scanned`;
  });

  await check('NU78-06', 'Dart mirrors the rules and its test iterates every vector', () => {
    const lib = fs.readFileSync(DART_LIB, 'utf8'), t = fs.readFileSync(DART_TEST, 'utf8');
    const need = [
      [/String\.fromEnvironment\(\s*'PAYESH_UPDATE_AUTO',\s*defaultValue: '0'/, 'pilot default OFF'],
      [/url\.scheme != 'https'/, 'https only'],
      [/Ed25519\(\)\.verify\(/, 'Ed25519 verification'],
      [/upd_rollback/, 'rollback floor'],
      [/status == 503 && _isFeatureDisabled/, '503 feature_disabled kill-switch'],
      [/upd_bad_hash/, 'hash refusal'],
      [/part\.deleteSync\(\)/, 'partial file deleted on mismatch'],
      [/maxUnconfirmedLaunches = 2/, 'rollback after unconfirmed launches'],
      [/'upd_expired'/, 'expiry'],
    ];
    const miss = need.filter(([re]) => !re.test(lib)).map(([, w]) => w);
    assert(!miss.length, 'Dart lib lacks: ' + miss.join(', '));
    assert(/native-update-vectors-78\.json/.test(t) && /for \(final c in cases\)/.test(t) && /expect\(_label\(d\), c\['expect'\]\)/.test(t), 'Dart test must iterate all vectors');
    assert(/NEGATIVE: one flipped byte/.test(t), 'Dart bad-hash test');
    return `${need.length} rules mirrored`;
  });

  await check('NU78-07', 'mutants: removing any single rule of the JS reference turns at least one vector red', async () => {
    const src = fs.readFileSync(TOOL, 'utf8');
    const MUT = [
      ['signature', "if (!crypto.verify(null, body, pk, sig)) bad('', 'upd_bad_signature');", ''],
      ['downgrade', 'if (m.build < floor)', 'if (false)'],
      ['expiry', "if (Date.parse(now) >= m.expiresMs) bad('', 'upd_expired');", ''],
      ['channel', "if (m.channel !== channel) bad(m.channel, 'upd_wrong_channel');", ''],
      ['halt', "if (m.halt) return { decision: 'halted', reason: 'publisher_halt' };", ''],
      ['https', "if (u.protocol !== 'https:' || !u.hostname) bad('artifact.url must be https');", ''],
      ['closed schema', "if (extra.length) bad(`${what}: unknown ${extra}`, code);", ''],
    ];
    const d = fs.mkdtempSync(path.join(os.tmpdir(), 'nu78m-'));
    let caught = 0;
    try {
      for (const [name, from, to] of MUT) {
        assert(src.includes(from), `mutant anchor missing: ${name}`);
        const f = path.join(d, `m-${caught}-${Date.now()}.mjs`);
        fs.writeFileSync(f, src.replace(from, to));
        const m = await import(pathToFileURL(f).href);
        const red = outcomes(m, v).some(([c, got]) => got !== c.expect);
        if (!red) throw new Error(`mutant "${name}" survived`);
        caught++;
      }
    } finally { fs.rmSync(d, { recursive: true, force: true }); }
    return `${caught}/${MUT.length} caught`;
  });

  console.log(`\nchecks=${passed + failed} pass=${passed} fail=${failed}`);
  console.log(failed ? `NATIVE-UPDATE-78-FAILED fail=${failed}` : `NATIVE-UPDATE-78-OK checks=${passed}`);
  process.exitCode = failed ? 1 : 0;
})();
