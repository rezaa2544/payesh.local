#!/usr/bin/env bash
# شاهد اجرای واقعی آزمون «ری‌استارت + دوام صف/ایدمپوتنسی» (ردیف ۲۷)
# اجرا: bash docs/cloud/reports/evidence/run-restart-evidence.sh
# خروجی موفق: docs/cloud/reports/evidence/sync-restart-run.log
# خروجی ناموفق: docs/cloud/reports/evidence/sync-restart-FAILED-<ts>.log (شاهد سالم بازنویسی نمی‌شود)
set -u
cd "$(dirname "$0")/../../../.." || { echo "FATAL: repo root not found"; exit 2; }

EVID=docs/cloud/reports/evidence
OUT="$EVID/sync-restart-run.log"
SHA=$(git rev-parse HEAD)
TS=$(date -u +%Y-%m-%dT%H:%M:%SZ)
TSFILE=$(echo "$TS" | tr -d ':-')
PRODUCT_SHA=$(git ls-tree -r HEAD | grep -v $'\tdocs/' | awk '{print $3"\t"$4}' | sha256sum | cut -d" " -f1)
TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT

set +e
node tests/restart.js > "$TMP" 2>&1
CODE=$?
set -e
BODY_SHA=$(sha256sum "$TMP" | cut -d" " -f1)
PASS=$(grep -c '✓' "$TMP" || true); [ -z "$PASS" ] && PASS=0
FAIL=$(grep -c '✗' "$TMP" || true); [ -z "$FAIL" ] && FAIL=0

write_log() {
  {
    echo "# ===== METADATA (generated by run-restart-evidence.sh) ====="
    echo "# commit_sha: $SHA"
    echo "# command: node tests/restart.js"
    echo "# product_tree_sha256: $PRODUCT_SHA"
    echo "# raw_output_sha256: $BODY_SHA"
    echo "# started_utc: $TS"
    echo "# note: raw test output follows verbatim; nothing was edited"
    echo "# ===== RAW OUTPUT ====="
    cat "$TMP"
    echo "# ===== FOOTER ====="
    echo "RESTART_SUMMARY pass=$PASS fail=$FAIL"
    echo "EXIT=$CODE"
  } > "$1"
}

if [ "$CODE" -ne 0 ] || [ "$FAIL" -ne 0 ] || [ "$PASS" -lt 1 ]; then
  BAD="$EVID/sync-restart-FAILED-$TSFILE.log"
  write_log "$BAD"
  echo "FAIL-CLOSED: restart witness failed (exit=$CODE pass=$PASS fail=$FAIL) → $BAD"
  exit 1
fi

write_log "$OUT"
echo "→ $OUT"
echo "pass=$PASS fail=$FAIL exit=$CODE"
echo "body_sha256=$BODY_SHA"
echo "product_tree_sha256=$PRODUCT_SHA"
