#!/usr/bin/env bash
# شاهد اجرای واقعی آزمون‌های مخزن — fail-closed + append-only
# اجرا:  bash docs/cloud/reports/evidence/run-tests-evidence.sh
# خروجی موفق:  docs/cloud/reports/evidence/mission-05-tests-run.log
#              + نسخهٔ آرشیوی append-only: tests-run-<sha7>-<ts>.log
# خروجی ناموفق: docs/cloud/reports/evidence/tests-run-FAILED-<ts>.log
#              (فایل شاهد سالم قبلی هرگز بازنویسی نمی‌شود — C-04)
#
# سخت‌سازی پس از بازبینی B (B-01 / C-01..C-04):
#   * هش SHA-256 بدنهٔ خام در سرصفحه ثبت و در دروازه بازمحاسبه می‌شود (C-02)
#   * تعداد آزمون‌های ثبت‌شده در tests/run.js جداگانه ثبت و مقایسه می‌شود (C-01)
#   * اثر انگشت درخت کامل منهای docs/ است، نه شش پوشه (C-03)
#   * اجرای ناموفق، شاهد سالم را از بین نمی‌برد (C-04)
set -u
cd "$(dirname "$0")/../../../.." || { echo "FATAL: repo root not found"; exit 2; }

EVID=docs/cloud/reports/evidence
OUT="$EVID/mission-05-tests-run.log"
mkdir -p "$EVID"

SHA=$(git rev-parse HEAD)
BR=$(git rev-parse --abbrev-ref HEAD)
TS=$(date -u +%Y-%m-%dT%H:%M:%SZ)
TSFILE=$(echo "$TS" | tr -d ':-')
NODE=$(node -v 2>/dev/null || echo "node-not-found")
OS=$(uname -srm 2>/dev/null || echo unknown)
DIRTY=$(git status --porcelain | wc -l | tr -d ' ')
CMD="npm test  (=> node --experimental-sqlite --disable-warning=ExperimentalWarning tests/run.js)"

# اثر انگشت درخت کامل به‌جز docs/ — هر تغییر در کد، وابستگی، نصب‌کننده یا CI آن را باطل می‌کند
PRODUCT_SHA=$(git ls-tree -r HEAD | grep -v $'\tdocs/' | awk '{print $3"\t"$4}' | sha256sum | cut -d" " -f1)
# تعداد آزمون‌های ثبت‌شده در رجیستری آزمون (مستقل از خروجی اجرا)
REGISTERED=$(grep -c 'await test(' tests/run.js)

TMP=$(mktemp)
trap 'rm -f "$TMP" "${BODY_TMP:-}"' EXIT

set +e
npm test > "$TMP" 2>&1
CODE=$?
set -e

BODY_TMP=$(mktemp)
cp "$TMP" "$BODY_TMP"
BODY_SHA=$(sha256sum "$BODY_TMP" | cut -d" " -f1)
BODY_LINES=$(wc -l < "$BODY_TMP" | tr -d ' ')
PASS=$(grep -c '✓' "$TMP" || true)
FAIL=$(grep -c '✗' "$TMP" || true)
[ -z "$PASS" ] && PASS=0
[ -z "$FAIL" ] && FAIL=0
FINAL_DIRTY=$(git status --porcelain | wc -l | tr -d ' ')

write_log() {  # $1 = مقصد
  {
    echo "# ===== METADATA (generated by run-tests-evidence.sh) ====="
    echo "# commit_sha: $SHA"
    echo "# branch: $BR"
    echo "# command: $CMD"
    echo "# node: $NODE"
    echo "# os: $OS"
    echo "# product_tree_sha256: $PRODUCT_SHA"
    echo "# product_tree_scope: all tracked files except docs/"
    echo "# tests_registered: $REGISTERED"
    echo "# raw_output_sha256: $BODY_SHA"
    echo "# raw_output_lines: $BODY_LINES"
    echo "# started_utc: $TS"
    echo "# working_tree_changes: $DIRTY"
    echo "# note: raw test output follows verbatim; nothing was edited"
    echo "# ===== RAW OUTPUT ====="
    cat "$BODY_TMP"
    echo "# ===== FOOTER ====="
    echo "SUMMARY pass=$PASS fail=$FAIL"
    echo "EXIT=$CODE"
    echo "REGISTERED=$REGISTERED"
    echo "FINAL_WORKING_TREE_CHANGES=$FINAL_DIRTY"
  } > "$1"
}

RC=0
if [ "$CODE" -ne 0 ]; then echo "FAIL-CLOSED: npm test exited $CODE"; RC=1; fi
if [ "$FAIL" -ne 0 ]; then echo "FAIL-CLOSED: $FAIL failing test(s)"; RC=1; fi
if [ "$PASS" -lt 1 ]; then echo "FAIL-CLOSED: no passing test detected — evidence is empty"; RC=1; fi
if [ "$PASS" -ne "$REGISTERED" ]; then echo "FAIL-CLOSED: $PASS passing but $REGISTERED registered tests"; RC=1; fi

if [ "$RC" -ne 0 ]; then
  BAD="$EVID/tests-run-FAILED-$TSFILE.log"
  write_log "$BAD"
  echo "→ $BAD (شاهد ناموفق؛ فایل شاهد سالم دست‌نخورده ماند)"
  exit "$RC"
fi

write_log "$OUT"
ARCHIVE="$EVID/tests-run-$(echo "$SHA" | cut -c1-7)-$TSFILE.log"
cp "$OUT" "$ARCHIVE"
echo "→ $OUT"
echo "→ $ARCHIVE (append-only)"
echo "pass=$PASS fail=$FAIL registered=$REGISTERED exit=$CODE"
echo "body_sha256=$BODY_SHA"
echo "product_tree_sha256=$PRODUCT_SHA"
exit 0
