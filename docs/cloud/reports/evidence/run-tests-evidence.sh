#!/usr/bin/env bash
# شاهد اجرای واقعی آزمون‌های مخزن — fail-closed
# اجرا:  bash docs/cloud/reports/evidence/run-tests-evidence.sh
# خروجی: docs/cloud/reports/evidence/mission-05-tests-run.log
#
# قواعد:
#   * خروجی خام آزمون بدون دست‌کاری ثبت می‌شود.
#   * متادیتا فقط در «سرصفحه» و «پاصفحهٔ» مشخص اضافه می‌شود.
#   * اگر آزمون شکست بخورد یا هیچ آزمونی اجرا نشود، اسکریپت با کد غیرصفر خارج می‌شود.
set -u
cd "$(dirname "$0")/../../../.." || { echo "FATAL: repo root not found"; exit 2; }

OUT=docs/cloud/reports/evidence/mission-05-tests-run.log
mkdir -p "$(dirname "$OUT")"

SHA=$(git rev-parse HEAD)
BR=$(git rev-parse --abbrev-ref HEAD)
TS=$(date -u +%Y-%m-%dT%H:%M:%SZ)
NODE=$(node -v 2>/dev/null || echo "node-not-found")
OS=$(uname -srm 2>/dev/null || echo unknown)
DIRTY=$(git status --porcelain | wc -l | tr -d ' ')
# اثر انگشت «کد محصول»: مستقل از commitهای مستندات، پس از هر commit قابل تطبیق است
PRODUCT_SHA=$(git ls-tree -r HEAD -- server client tests installer scripts desktop | sha256sum | cut -d" " -f1)
CMD="npm test  (=> node --experimental-sqlite --disable-warning=ExperimentalWarning tests/run.js)"

TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT

set +e
npm test > "$TMP" 2>&1
CODE=$?
set -e

PASS=$(grep -c '✓' "$TMP" || true)
FAIL=$(grep -c '✗' "$TMP" || true)
[ -z "$PASS" ] && PASS=0
[ -z "$FAIL" ] && FAIL=0

{
  echo "# ===== METADATA (generated by run-tests-evidence.sh) ====="
  echo "# commit_sha: $SHA"
  echo "# branch: $BR"
  echo "# command: $CMD"
  echo "# node: $NODE"
  echo "# os: $OS"
  echo "# product_tree_sha256: $PRODUCT_SHA"
  echo "# started_utc: $TS"
  echo "# working_tree_changes: $DIRTY"
  echo "# note: raw test output follows verbatim; nothing was edited"
  echo "# ===== RAW OUTPUT ====="
  cat "$TMP"
  echo "# ===== FOOTER ====="
  echo "SUMMARY pass=$PASS fail=$FAIL"
  echo "EXIT=$CODE"
} > "$OUT"

echo "→ $OUT (pass=$PASS fail=$FAIL exit=$CODE sha=$SHA)"

RC=0
if [ "$CODE" -ne 0 ]; then echo "FAIL-CLOSED: npm test exited $CODE"; RC=1; fi
if [ "$FAIL" -ne 0 ]; then echo "FAIL-CLOSED: $FAIL failing test(s)"; RC=1; fi
if [ "$PASS" -lt 1 ]; then echo "FAIL-CLOSED: no passing test detected — evidence is empty"; RC=1; fi
if ! grep -q '^EXIT=' "$OUT"; then echo "FAIL-CLOSED: footer missing"; RC=1; fi
exit $RC
